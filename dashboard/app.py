def render_sidebar():
    """Render the navigation sidebar."""
    with st.sidebar:
        st.title("🏥 PhysioGuard Remote Patient Monitoring")
        st.markdown("*AI-driven early warning system for dependent elderly and home-care patients.*")
        st.markdown("---")
        
        runs = get_runs()
        selected_run = None
        if runs:
            selected_run = st.selectbox("Select Pipeline Run", runs)
        else:
            st.error("No outputs found. Run pipeline first.")
            st.stop()
            
        st.markdown("---")
        
        page = st.radio(
            "Navigate",
            [
                "🏠 Ward Overview",
                "👤 Patient Deep-Dive",
                "🔍 Explainability (SHAP & Captum)",
                "🌐 Federated Learning",
                "🌍 Domain Generalization",
            ],
            label_visibility="collapsed",
        )
        
        st.markdown("---")
        st.markdown("#### Model Info")
        _, model, ensemble_weights, _, _ = load_run_data(selected_run)
        if ensemble_weights is not None:
            st.success("Model: Hybrid Ensemble (CatBoost + TCN-Transformer)")
            st.caption(f"Weights: {ensemble_weights[0]:.2f} / {ensemble_weights[1]:.2f}")
        elif model:
            st.success("Model: CatBoost Baseline")
        else:
            st.warning("Model `ensemble.pkl` or `model.cbm` not found.")
            
        st.markdown("---")
        st.caption("v3.0 - Modular Config-Driven Architecture")
        
    return page, selected_run


