def render_patient_deepdive(df: pd.DataFrame, model, feature_cols: list[str]):
    """Individual patient analysis with vital trends and SHAP."""
    st.markdown('<div class="section-header">👤 Patient Deep-Dive</div>', unsafe_allow_html=True)
    
    episodes = sorted(df[EPISODE_COLUMN].unique())
    
    # Find interesting episodes (those with deterioration)
    det_episodes = df[df[TARGET_COLUMN] == 1][EPISODE_COLUMN].unique()
    
    col1, col2 = st.columns([1, 3])
    with col1:
        selected_ep = st.selectbox(
            "Select Patient Episode",
            episodes,
            index=0 if len(det_episodes) == 0 else int(np.where(episodes == det_episodes[0])[0][0]),
        )
        if len(det_episodes) > 0:
            st.info(f"💡 {len(det_episodes)} episodes have deterioration events")
    
    episode = df[df[EPISODE_COLUMN] == selected_ep].sort_values(HOUR_COLUMN)
    
    with col2:
        # Patient summary
        risk = episode["deterioration_risk"].iloc[-1]
        color = "#ff4444" if risk >= 0.6 else "#ff8c00" if risk >= 0.3 else "#00c853"
        status = "HIGH RISK" if risk >= 0.6 else "MODERATE" if risk >= 0.3 else "LOW RISK"
        
        st.markdown(f"""
        <div style="display:flex;gap:20px;align-items:center;padding:12px 20px;
                    background:linear-gradient(135deg,{color}20,transparent);
                    border-left:4px solid {color};border-radius:0 12px 12px 0;">
            <div>
                <span style="font-size:2rem;font-weight:700;color:{color}">{risk:.1%}</span>
                <span style="color:{color};font-weight:600;margin-left:8px">{status}</span>
            </div>
            <div style="color:#8892b0">
                Age: {episode['age'].iloc[0]} | 
                Hours monitored: {len(episode)} |
                NEWS: {episode.get('news_score', pd.Series([0])).iloc[-1]}
            </div>
        </div>
        """, unsafe_allow_html=True)
    
    # Vital sign trends
    st.markdown("### 📊 Vital Sign Trends")
    vitals = ["heart_rate", "respiratory_rate", "spo2_pct", "systolic_bp", "temperature_c", "lactate"]
    vital_titles = ["Heart Rate", "Respiratory Rate", "SpO2 %", "Systolic BP", "Temperature °C", "Lactate"]
    
    fig = make_subplots(rows=2, cols=3, subplot_titles=vital_titles, vertical_spacing=0.12)
    
    for i, (vital, title) in enumerate(zip(vitals, vital_titles)):
        row = i // 3 + 1
        col = i % 3 + 1
        
        if vital in episode.columns:
            fig.add_trace(
                go.Scatter(
                    x=episode[HOUR_COLUMN], y=episode[vital],
                    mode="lines+markers", name=title,
                    line=dict(width=2),
                    marker=dict(size=4),
                ),
                row=row, col=col,
            )
    
    fig.update_layout(
        height=400,
        template="plotly_dark",
        paper_bgcolor="rgba(0,0,0,0)",
        plot_bgcolor="rgba(0,0,0,0)",
        showlegend=False,
        font=dict(family="Inter", size=11),
    )
    st.plotly_chart(fig, use_container_width=True)
    
    # Risk timeline
    st.markdown("### 📉 Risk Score Timeline (AI vs NEWS)")
    fig2 = go.Figure()
    fig2.add_trace(go.Scatter(
        x=episode[HOUR_COLUMN], y=episode["deterioration_risk"],
        mode="lines+markers", name="AI Risk Score",
        line=dict(color="#64ffda", width=3),
        fill="tozeroy", fillcolor="rgba(100,255,218,0.1)",
    ))
    
    if "news_score" in episode.columns:
        news_norm = episode["news_score"] / max(episode["news_score"].max(), 1)
        fig2.add_trace(go.Scatter(
            x=episode[HOUR_COLUMN], y=news_norm,
            mode="lines+markers", name="NEWS (normalized)",
            line=dict(color="#ff8c00", width=2, dash="dot"),
        ))
    
    # Mark actual deterioration points
    det_points = episode[episode[TARGET_COLUMN] == 1]
    if len(det_points) > 0:
        fig2.add_trace(go.Scatter(
            x=det_points[HOUR_COLUMN], y=det_points["deterioration_risk"],
            mode="markers", name="Actual Deterioration",
            marker=dict(color="#ff4444", size=12, symbol="x"),
        ))
    
    fig2.update_layout(
        height=300,
        template="plotly_dark",
        paper_bgcolor="rgba(0,0,0,0)",
        plot_bgcolor="rgba(0,0,0,0)",
        font=dict(family="Inter"),
        yaxis_title="Risk Score",
        xaxis_title="Hours from Admission",
    )
    st.plotly_chart(fig2, use_container_width=True)


