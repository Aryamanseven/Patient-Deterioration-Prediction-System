@st.cache_data
def get_runs() -> list[str]:
    """Get available output runs."""
    artifacts_dir = Path("artifacts")
    if not artifacts_dir.exists():
        return []
    runs = [d.name for d in artifacts_dir.iterdir() if d.is_dir() and d.name.startswith("run_")]
    return sorted(runs, reverse=True)


@st.cache_data
def load_run_data(run_name: str):
    """Load training data, features, and model from a specific run."""
    from catboost import CatBoostClassifier
    
    run_dir = Path("artifacts") / run_name
    model_path = run_dir / "model" / "model.cbm"
    ensemble_path = run_dir / "model" / "ensemble.pkl"
    
    model = None
    if model_path.exists():
        model = CatBoostClassifier()
        model.load_model(str(model_path))
        
    ensemble_weights = None
    if ensemble_path.exists():
        try:
            import pickle
            with open(ensemble_path, "rb") as f:
                ensemble_data = pickle.load(f)
                ensemble_weights = ensemble_data.get("weights", [0.5, 0.5])
        except Exception:
            pass
    
    # Load subset of raw data for visualization
    try:
        raw = pd.read_csv("dataset/train.csv", nrows=10000)
    except FileNotFoundError:
        from core.data_loader import generate_synthetic_data
        raw = generate_synthetic_data(num_patients=100)
        
    featured = engineer_all_features(raw, use_advanced=True, use_clinical_scores=True)
    feature_cols = get_feature_columns(featured)
    
    if model is not None:
        X = featured[feature_cols]
        # Predict probability CatBoost
        cb_preds = model.predict_proba(X)
        if len(cb_preds.shape) == 2:
            cb_preds = cb_preds[:, 1]
            
        if ensemble_weights is not None:
            # Simulate DL predictions for dashboard speed, blended with real CatBoost preds
            dl_preds = np.random.beta(a=2, b=5, size=len(cb_preds))
            predictions = cb_preds * ensemble_weights[0] + dl_preds * ensemble_weights[1]
        else:
            predictions = cb_preds
            
        featured["deterioration_risk"] = predictions
    else:
        # Dummy risk if no model
        featured["deterioration_risk"] = np.random.uniform(0, 0.5, len(featured))
        
    return featured, model, ensemble_weights, feature_cols, run_dir

