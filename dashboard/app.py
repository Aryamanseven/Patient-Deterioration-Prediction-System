def render_ward_overview(df: pd.DataFrame):
    """Ward-level patient overview with risk cards."""
    st.markdown('<div class="section-header">🏠 Ward Overview — Patient Risk Triage</div>', unsafe_allow_html=True)
    
    # Get latest status per episode
    latest = df.groupby(EPISODE_COLUMN).last().reset_index()
    latest["risk_band"] = pd.cut(
        latest["deterioration_risk"],
        bins=[-0.01, 0.3, 0.6, 1.01],
        labels=["Low", "Moderate", "High"]
    )
    
    # Summary metrics
    n_total = len(latest)
    n_high = (latest["risk_band"] == "High").sum()
    n_moderate = (latest["risk_band"] == "Moderate").sum()
    n_low = (latest["risk_band"] == "Low").sum()
    
    cols = st.columns(4)
    metrics = [
        ("Total Patients", n_total, "🏥"),
        ("High Risk", n_high, "🔴"),
        ("Moderate Risk", n_moderate, "🟠"),
        ("Low Risk", n_low, "🟢"),
    ]
    
    for col, (label, value, icon) in zip(cols, metrics):
        with col:
            st.markdown(f"""
            <div class="metric-tile">
                <p style="font-size:1.5rem;margin:0">{icon}</p>
                <p class="metric-value">{value}</p>
                <p class="metric-label">{label}</p>
            </div>
            """, unsafe_allow_html=True)
    
    st.markdown("<br>", unsafe_allow_html=True)
    
    # Risk distribution chart
    col1, col2 = st.columns([2, 1])
    with col1:
        fig = px.histogram(
            latest, x="deterioration_risk", 
            color="risk_band",
            color_discrete_map={"High": "#ff4444", "Moderate": "#ff8c00", "Low": "#00c853"},
            nbins=50,
            title="Patient Risk Score Distribution",
            labels={"deterioration_risk": "AI Risk Score", "count": "Patients"},
        )
        fig.update_layout(
            template="plotly_dark",
            paper_bgcolor="rgba(0,0,0,0)",
            plot_bgcolor="rgba(0,0,0,0)",
            font=dict(family="Inter"),
        )
        st.plotly_chart(fig, use_container_width=True)
    
    with col2:
        fig = go.Figure(data=[go.Pie(
            labels=["High", "Moderate", "Low"],
            values=[n_high, n_moderate, n_low],
            marker=dict(colors=["#ff4444", "#ff8c00", "#00c853"]),
            hole=0.5,
            textinfo="percent+label",
        )])
        fig.update_layout(
            title="Risk Distribution",
            template="plotly_dark",
            paper_bgcolor="rgba(0,0,0,0)",
            font=dict(family="Inter"),
            showlegend=False,
            height=350,
        )
        st.plotly_chart(fig, use_container_width=True)
    
    # High-risk patient list
    st.markdown('<div class="section-header">⚠️ High-Risk Patients — Immediate Attention Required</div>', unsafe_allow_html=True)
    
    high_risk = latest[latest["risk_band"] == "High"].sort_values("deterioration_risk", ascending=False).head(10)
    
    if len(high_risk) == 0:
        st.success("No high-risk patients currently monitored.")
        
    for _, patient in high_risk.iterrows():
        risk = patient["deterioration_risk"]
        ep_id = patient[EPISODE_COLUMN]
        age = patient.get("age", "N/A")
        hr = patient.get("heart_rate", "N/A")
        rr = patient.get("respiratory_rate", "N/A")
        spo2 = patient.get("spo2_pct", "N/A")
        news = patient.get("news_score", "N/A")
        
        if risk >= 0.8:
            badge_class = "alert-critical"
            badge_text = "CRITICAL"
        elif risk >= 0.6:
            badge_class = "alert-warning"
            badge_text = "HIGH"
        else:
            badge_class = "alert-normal"
            badge_text = "WATCH"
        
        hr_val = f"{hr:.0f}" if isinstance(hr, (int, float)) else hr
        rr_val = f"{rr:.0f}" if isinstance(rr, (int, float)) else rr
        spo2_val = f"{spo2:.1f}" if isinstance(spo2, (int, float)) else spo2
        news_val = f"{news:.0f}" if isinstance(news, (int, float)) else news
        
        st.markdown(f"""
        <div class="risk-high" style="display:flex;justify-content:space-between;align-items:center;">
            <div>
                <strong>Patient #{ep_id}</strong> | Age: {age} | 
                HR: {hr_val} | RR: {rr_val} | SpO2: {spo2_val}% | NEWS: {news_val}
            </div>
            <div>
                <span class="alert-badge {badge_class}">{badge_text}</span>
                <strong style="margin-left:12px">Risk: {risk:.1%}</strong>
            </div>
        </div>
        """, unsafe_allow_html=True)


