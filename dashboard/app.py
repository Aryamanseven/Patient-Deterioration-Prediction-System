def render_shap_page(run_dir: Path):
    """Explainability visualizations."""
    st.markdown('<div class="section-header">🔍 Model Explainability (SHAP & Captum)</div>', unsafe_allow_html=True)
    
    tab1, tab2 = st.tabs(["📊 CatBoost (SHAP - Tabular)", "🔥 TCN-Transformer (Captum - Temporal)"])
    
